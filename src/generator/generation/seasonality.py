"""Сезонные циклы: суточная и годовая динамика как чистые функции времени.

Генерация метрик строится из трёх компонент:
    значение = базовый климат + годовая сезонность + суточная сезонность + шум.

Функции возвращают множитель в диапазоне ``[-1, 1]``. Отделение «чистой»
математики сезонности от конкретных метрик делает логику прозрачной и
легко тестируемой на фиксированных моментах времени.
"""

from __future__ import annotations

import math
from datetime import datetime


def diurnal_factor(at: datetime) -> float:
    """Суточный множитель: пик около 15:00, минимум около 03:00.

    Холоднее всего незадолго до рассвета, теплее всего — во второй половине дня.
    """
    hour = at.hour + at.minute / 60.0 + at.second / 3600.0
    # cos(2π * (hour - 15) / 24): 1 в 15:00, -1 в 03:00.
    return math.cos(2.0 * math.pi * (hour - 15.0) / 24.0)


def annual_factor(at: datetime) -> float:
    """Годовой множитель для северного полушария.

    Максимум — середина июля (~день 196), минимум — середина января.
    """
    day_of_year = float(at.timetuple().tm_yday)
    return math.cos(2.0 * math.pi * (day_of_year - 196.0) / 365.25)
