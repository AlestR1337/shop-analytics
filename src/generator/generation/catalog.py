class UserCatalog:
    """Генератор справочника пользователей."""

    def __init__(
        self,
        cities: list[str],
        count: int,
        seed: int,
        as_of: datetime,
    ) -> None:
        if not cities:
            raise ValueError("Список городов пуст")

        if count <= 0:
            raise ValueError("Количество пользователей должно быть положительным")

        self._cities = cities
        self._count = count
        self._seed = seed
        self._as_of = as_of

    def users(self) -> list[User]:
        rng = random.Random(self._seed)

        city_weights = [
            _CITY_WEIGHTS.get(city, 5)
            for city in self._cities
        ]

        return [
            User(
                user_id=index,
                city=rng.choices(
                    self._cities,
                    weights=city_weights,
                    k=1,
                )[0],
                registered_at=(
                    self._as_of
                    - timedelta(days=rng.randint(1, 730))
                ),
            )
            for index in range(1, self._count + 1)
        ]
